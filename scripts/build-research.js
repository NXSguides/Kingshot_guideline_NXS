#!/usr/bin/env node
/* Builds the public research pages' shell from the officer page, so they look the same without copying anything by hand:
     css/research.css        ← every <style> block of officer-x7k2p9.html
     research-x7k2p9.html    ← one <section> per public report (markup copied from the officer page) + a small loader
   The loader runs the officer report code itself (js/officer/<report>.js) with a stand-in OFFICER object, then hides what is
   not for members: the "not known yet" card, the folded "how we worked it out" part (sources, names, counts, formulas), the
   video card and the Bear-analysis chips. Which reports are public is the PUBLIC list below (Sherry 2026-11-20).
   Run after changing the officer page's styles or a report's section markup:  node scripts/build-research.js            */
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, ".."), off = fs.readFileSync(path.join(root, "officer-x7k2p9.html"), "utf8");
const PUBLIC = [["rg", "rg", "rg"], ["bh", "bh", "bh"], ["ls", "ls", "ls"], ["tb", "tb", "tb"], ["ma", "ma", "ma"], ["hr", "growth", "growth"]];   // [section id, js file, OFFICER_PAGES key]
const css = [...off.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");
fs.writeFileSync(path.join(root, "css/research.css"), "/* GENERATED by scripts/build-research.js from officer-x7k2p9.html — do not edit */\n" + css);
const sec = (id) => { const m = off.match(new RegExp(`<section class="pg" id="pg-${id}" hidden>[\\s\\S]*?</section>`)); if (!m) throw new Error("no section " + id); return m[0]; };
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow">
<title>NXS research</title>
<link rel="icon" type="image/png" sizes="32x32" href="icons/favicon-32.png">
<link rel="stylesheet" href="css/styles.css">
<link rel="stylesheet" href="css/research.css">
<style>
  /* GENERATED by scripts/build-research.js — PREVIEW of the public research pages, not linked from anywhere yet. */
  body { padding: 16px 16px 60px; }
  .pub-top { display: flex; justify-content: flex-end; gap: 8px; margin-bottom: 4px; }
  .pub-top select { padding: 6px 8px; border: 1px solid var(--rule); border-radius: 8px; background: var(--panel); color: var(--text); font: inherit; }
  .pub-lock { border: 1px dashed var(--rule); border-radius: 10px; padding: 8px 12px; margin: 0 0 10px; font-size: 13px; color: var(--text-muted); }
  .pub-hide { display: none !important; }
</style>
</head>
<body>
<div class="wrap" id="main">
  <div class="pub-top"><select id="pub_lang" aria-label="Language"></select></div>
  <div class="pub-lock" id="pub_lock"></div>
${PUBLIC.map(([id]) => sec(id)).join("\n")}
${sec("growth")}
</div>
<script src="data/research-i18n.js"></script>
<script>
(function () {
  const PUBLIC = ${JSON.stringify(PUBLIC)};
  const LANGS = { en: "English", zh: "繁體中文", ko: "한국어", de: "Deutsch", fr: "Français", pt: "Português", es: "Español", tr: "Türkçe", id: "Bahasa Indonesia", ru: "Русский", th: "ไทย", ar: "العربية" };
  const LOCK = { en: "Preview: this page is not linked from the site yet.", zh: "預覽：這一頁還沒有接到網站的選單上。", pt: "Prévia: esta página ainda não está ligada ao site.", ar: "معاينة: هذه الصفحة غير مرتبطة بالموقع بعد.", ko: "미리보기: 이 페이지는 아직 사이트에 연결되지 않았어." };
  const RT = window.RESEARCH_T || {};
  for (const l in ((RT.vv || {}).T || {})) if (RT.vv.T[l].lock) LOCK[l] = RT.vv.T[l].lock;
  /* de fr es tr id ru th: the officer report files only carry 5 languages, the rest is laid over English here */
  const deep = (base, add) => { if (add === null || typeof add !== "object") return add; const o = Array.isArray(base) ? base.slice() : { ...(base || {}) }; for (const k of Object.keys(add)) o[k] = deep(base ? base[k] : undefined, add[k]); return o; };
  window.RESEARCH_MERGE = (rep, tables) => { const R = RT[rep]; if (!R) return;
    for (const [name, tb] of Object.entries(tables)) { const add = R[name]; if (!add) continue;
      if (name === "HN") { for (const l in add) for (const id in add[l]) if (tb[id]) tb[id][l] = add[l][id]; continue; }
      for (const l in add) tb[l] = deep(tb.en, add[l]); } };
  const q = new URLSearchParams(location.search);
  const rep = PUBLIC.find((p) => p[0] === q.get("r")) || PUBLIC[0];
  let lang = q.get("lang") || ""; if (!LANGS[lang]) { try { lang = localStorage.getItem("ks-lang") || ""; } catch (e) {} } if (!LANGS[lang]) lang = "en";
  const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  /* stand-in for the officer page: no videos, no links into officer tabs */
  window.OFFICER = { lang, util: { esc }, vidCard: () => "", bearChips: () => "" };
  window.OFFICER_PAGES = {};
  /* not for members: headings that start with one of these marks → the whole card / folded block is hidden */
  const HIDE = ["🟡", "🔢", "📑", "📈", "📺"];
  const sectionEl = document.getElementById("pg-" + rep[0]);
  const filter = () => {
    sectionEl.querySelectorAll(".card, details").forEach((c) => { const h = c.querySelector(":scope > h3, :scope > summary, :scope > h4"); if (h && (HIDE.some((m) => h.textContent.trim().startsWith(m)) || h.textContent.includes("🟡"))) c.classList.add("pub-hide"); });
    sectionEl.querySelectorAll("li, p, div, span").forEach((e) => { if (!e.children.length && e.textContent.trim().startsWith("🟡")) e.classList.add("pub-hide"); });   // single "not known / guess" lines
    const w = document.createTreeWalker(sectionEl, NodeFilter.SHOW_TEXT); let n;   // "(Sparrow 11/03)"-style source notes: no names on a public page
    while ((n = w.nextNode())) { const v = n.nodeValue.replace(/\\s*[（(][^（()）]*(?:Sparrow|Sherry)[^（()）]*[)）]/g, ""); if (v !== n.nodeValue) n.nodeValue = v; }
    sectionEl.querySelectorAll('a[href^="#"]').forEach((a) => a.classList.add("pub-hide"));   // links to other officer tabs
  };
  const setTexts = () => { document.documentElement.lang = lang === "zh" ? "zh-Hant" : lang; document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.getElementById("pub_lock").textContent = LOCK[lang];
    const h = sectionEl.querySelector("h1"); if (h) document.title = h.textContent.replace(/^\\S+\\s/, ""); };
  const sel = document.getElementById("pub_lang");
  sel.innerHTML = Object.entries(LANGS).map(([c, n]) => '<option value="' + c + '"' + (c === lang ? " selected" : "") + ">" + n + "</option>").join("");
  const s = document.createElement("script"); s.src = "js/officer/" + rep[1] + ".js";
  s.onload = () => { const pg = OFFICER_PAGES[rep[2]]; sectionEl.hidden = false;
    new MutationObserver(filter).observe(sectionEl, { childList: true, subtree: true });
    pg.init(); filter(); setTexts();
    sel.onchange = () => { lang = sel.value; OFFICER.lang = lang; pg.setLang(lang); filter(); setTexts(); }; };
  document.body.appendChild(s);
})();
</script>
</body>
</html>
`;
fs.writeFileSync(path.join(root, "research-x7k2p9.html"), html);
console.log("research: " + PUBLIC.length + " reports, css " + Math.round(css.length / 1024) + " KB");
